/** Add stable body classes for CSS and child themes. */
function body_classes( array $classes ): array {
	if ( class_exists( 'WooCommerce' ) ) {
		$classes[] = 'maintheme-has-woocommerce';
	}
	if ( defined( 'MAINTHEME_IR_COMMERCE_VERSION' ) ) {
		$classes[] = 'maintheme-has-iran-commerce';
	}
	if ( is_child_theme() ) {
		$classes[] = 'maintheme-child-' . sanitize_html_class( get_stylesheet() );
	}
	return $classes;
}
add_filter( 'body_class', __NAMESPACE__ . '\\body_classes' );

/**
 * Keep WooCommerce's default English page titles Persian on the storefront.
 * Merchant-customized titles are left untouched.
 */
function page_titles( string $title, int $post_id ): string {
	if ( is_admin() || ! function_exists( 'wc_get_page_id' ) ) {
		return $title;
	}

	$defaults = array(
		'Shop'       => __( 'فروشگاه', 'maintheme' ),
		'Cart'       => __( 'سبد خرید', 'maintheme' ),
		'Checkout'   => __( 'تسویه حساب', 'maintheme' ),
		'My account' => __( 'حساب کاربری', 'maintheme' ),
	);
	$page_ids = array_filter( array_map( 'wc_get_page_id', array( 'shop', 'cart', 'checkout', 'myaccount' ) ) );

	return isset( $defaults[ $title ] ) && in_array( $post_id, $page_ids, true ) ? $defaults[ $title ] : $title;
}
add_filter( 'the_title', __NAMESPACE__ . '\\page_titles', 20, 2 );

/**
 * Add stable theme-owned classes to each product card generated by the Product
 * Template block. This isolates child themes from WooCommerce internal classes.
 */
function product_card_classes( string $block_content, array $block ): string {
	if ( '' === trim( $block_content ) ) {
		return $block_content;
	}

	$classes = array( 'maintheme-product-card' );
	$template_class = (string) ( $block['attrs']['className'] ?? '' );
	if ( false !== strpos( $template_class, 'maintheme-product-template--compact' ) ) {
		$classes[] = 'maintheme-product-card--compact';
	}
	if ( false !== strpos( $template_class, 'maintheme-product-template--minimal' ) ) {
		$classes[] = 'maintheme-product-card--minimal';
	}
	$classes = (array) apply_filters( 'maintheme_product_card_classes', $classes, $block );

	if ( class_exists( '\\WP_HTML_Tag_Processor' ) ) {
		$processor = new \WP_HTML_Tag_Processor( $block_content );
		while ( $processor->next_tag( 'li' ) ) {
			foreach ( array_filter( array_unique( $classes ) ) as $class ) {
				$processor->add_class( sanitize_html_class( $class ) );
			}
		}
		return $processor->get_updated_html();
	}

	$class_string = implode( ' ', array_map( 'sanitize_html_class', array_filter( $classes ) ) );
	return (string) preg_replace( '/<li(\s+class=")/i', '<li$1' . esc_attr( $class_string ) . ' ', $block_content );
}
add_filter( 'render_block_woocommerce/product-template', __NAMESPACE__ . '\\product_card_classes', 20, 2 );
